-- ※ MySQL과 Oracle의 차이
--   1) MySQL의 '스키마(sampledb)'는 Oracle에서 '사용자(스키마)'에 해당한다.
--      SYSTEM 스키마에는 데이터관리 수업의 STUDENT 테이블이 이미 있으므로,
--      강의자료처럼 별도의 SAMPLEDB 스키마를 만들어 그 안에 student 테이블을 둔다.
--      (NO AUTHENTICATION: 비밀번호가 없고 로그인도 하지 않는 '스키마 전용' 계정)
--   2) MySQL의 USE sampledb 대신 ALTER SESSION SET CURRENT_SCHEMA 를 사용한다.
--   3) Oracle은 INSERT/UPDATE/DELETE 후 COMMIT 해야 다른 접속(자바 프로그램)에서 보인다.
--   4) 한글이 잘리지 않도록 VARCHAR2 길이를 '문자(CHAR)' 단위로 지정한다.

-- ========================================================================================
-- 1. 스키마 생성 (슬라이드 29~30) : sampledb
-- ========================================================================================
CREATE USER sampledb NO AUTHENTICATION
    DEFAULT TABLESPACE users
    QUOTA UNLIMITED ON users;

-- 이후 SQL은 sampledb 스키마를 기준으로 실행 (MySQL의 USE sampledb)
ALTER SESSION SET CURRENT_SCHEMA = sampledb;

-- ========================================================================================
-- 2. 테이블 생성 (슬라이드 31~33)
--    name : varchar 10자, NOT NULL
--    dept : varchar 20자, NOT NULL
--    id   : char 7자, PRIMARY KEY
-- ========================================================================================
CREATE TABLE student (
    name VARCHAR2(10 CHAR) NOT NULL,
    dept VARCHAR2(20 CHAR) NOT NULL,
    id   CHAR(7)           PRIMARY KEY
);

-- ========================================================================================
-- 3. 레코드 추가 (슬라이드 34~35)
-- ========================================================================================
insert into student (name, dept, id) values ('김철수', '컴퓨터시스템', '1091011');
insert into student (name, dept, id) values ('최고봉', '멀티미디어', '0792012');
insert into student (name, dept, id) values ('이기자', '컴퓨터공학', '0494013');
COMMIT;

-- ========================================================================================
-- 4. 데이터 검색 (슬라이드 36~37)
-- ========================================================================================
select name, dept, id from student where dept='컴퓨터공학';
select * from student where dept='컴퓨터공학';

-- ========================================================================================
-- 5. 데이터 수정 (슬라이드 38~40)
--    (MySQL Workbench의 Safe Updates 옵션은 Oracle에는 없으므로 설정 변경 불필요)
-- ========================================================================================
update student set dept='컴퓨터공학' where name='최고봉';
COMMIT;
select * from student;

-- ========================================================================================
-- 6. 레코드 삭제 (슬라이드 41~42)
-- ========================================================================================
delete from student where name='최고봉';
COMMIT;
select * from student;
